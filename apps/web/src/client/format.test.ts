import { expect, test } from "vitest";
import { formatYen } from "./format";

test.each([
  ["0", "0"],
  ["999", "999"],
  ["1000", "1,000"],
  ["128100", "128,100"],
  ["65088550.25", "65,088,550"],
  ["0.4999", "0"],
  ["0.5", "1"],
  ["1.49999999", "1"],
  ["999.5", "1,000"],
  ["999999.5", "1,000,000"],
  ["99999999999999999999.99999999", "100,000,000,000,000,000,000"],
  ["123456789012345678901234.12345678", "123,456,789,012,345,678,901,234"],
])("%s は円未満を四捨五入して 3 桁区切りにする", (amount, expected) => {
  expect(formatYen(amount)).toBe(expected);
});

test.each(["", "-1", "1e3", "1,000", "01", ".5", "1.", " 1", "NaN", "１"])(
  "10進の表記でない %j は null にする",
  (amount) => {
    expect(formatYen(amount)).toBeNull();
  },
);
